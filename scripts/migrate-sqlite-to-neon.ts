import "dotenv/config";
import Database from "better-sqlite3";
import { resolve } from "node:path";
import { neon } from "@neondatabase/serverless";
if (!process.env.DATABASE_URL) throw Error("DATABASE_URL is required");
const source = resolve(process.argv[2] || process.env.DB_PATH || "data/level-up.sqlite");
const db = new Database(source, { readonly: true });
const profile = db.prepare("SELECT data FROM profile_settings WHERE id='local'").get() as { data: string } | undefined;
if (!profile) throw Error(`No Level Up profile found in ${source}`);
const state = JSON.parse(profile.data);
const maps = { templates: "quest_templates", instances: "quest_instances", ledger: "score_ledger", logs: "daily_logs", audit: "audit_events", events: "completion_events", jobs: "notification_jobs" } as const;
for (const [key, table] of Object.entries(maps)) state[key] = db.prepare(`SELECT data FROM ${table} ORDER BY rowid`).all().map((r: any) => JSON.parse(r.data));
db.close();
const sql = neon(process.env.DATABASE_URL);
await sql`CREATE TABLE IF NOT EXISTS app_state (id text PRIMARY KEY, data jsonb NOT NULL, updated_at timestamptz NOT NULL DEFAULT now())`;
const existing = await sql`SELECT updated_at FROM app_state WHERE id='owner'`;
if (existing.length && !process.argv.includes("--replace")) throw Error("Neon already has owner state. Re-run with --replace only if you intend to overwrite it.");
await sql`INSERT INTO app_state(id,data,updated_at) VALUES ('owner', ${JSON.stringify(state)}::jsonb, now()) ON CONFLICT(id) DO UPDATE SET data=excluded.data,updated_at=now()`;
console.log(`Migrated ${state.instances.length} quests, ${state.logs.length} daily logs, and ${state.ledger.length} ledger entries from ${source} to Neon.`);
